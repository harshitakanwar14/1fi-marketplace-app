// Helper to build EMI plans
const emi = (id: string, price: number, tenures: number[], noCostSavings = 0) =>
  tenures.map(t => ({
    id: `${id}-${t}`,
    tenureMonths: t,
    monthlyAmount: Math.ceil(price / t),
    isNoCost: true,
    interestRatePct: 0,
    processingFee: 0,
    totalPayable: price,
    savingsAmount: noCostSavings,
  }));

